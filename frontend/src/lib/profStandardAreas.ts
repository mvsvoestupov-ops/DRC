export function getAreaLabel(code?: string | null): string | null {
  if (!code) return null;
  const normalized = code.padStart(2, '0');
  return PROF_STANDARD_AREAS.find((a) => a.code === normalized)?.name ?? code;
}

export function areaCodeFromPsCode(psCode?: string | null): string | null {
  if (!psCode) return null;
  const match = psCode.trim().match(/^(\d{2})\./);
  return match ? match[1] : null;
}

export function getStandardAreaCode(item: {
  professional_area_code?: string | null;
  ps_code?: string | null;
}): string | null {
  if (item.professional_area_code) {
    return item.professional_area_code.padStart(2, '0');
  }
  return areaCodeFromPsCode(item.ps_code);
}
