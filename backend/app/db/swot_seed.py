def _pick(topic: str, field: str, table_no: int) -> str:
    flavor = TABLE_FLAVOR[table_no]
    variants = BASE[topic][field]
    return variants[(table_no - 1) % len(variants)].format(flavor=flavor)


def seed_swot_demo(*, force: bool = True) -> dict:
    """
    Заполняет анализы SWOT для admin (или первого пользователя).
    force=True — перезаписывает существующие тексты.
    """
    session = SessionLocal()
    try:
        user = (
            session.query(User).filter(User.email == "admin@aonk.ru").first()
            or session.query(User).filter(User.role == "admin").first()
            or session.query(User).order_by(User.id.asc()).first()
        )
        if not user:
            return {"ok": False, "error": "no_user"}

        tables = session.query(SwotTable).order_by(SwotTable.number.asc()).all()
        if len(tables) < SWOT_TABLE_COUNT:
            return {"ok": False, "error": "tables_incomplete", "count": len(tables)}

        created = 0
        updated = 0
        skipped = 0
        for table in tables:
            for topic in SWOT_TOPICS:
                row = (
                    session.query(SwotAnalysis)
                    .filter(
                        SwotAnalysis.table_id == table.id,
                        SwotAnalysis.user_id == user.id,
                        SwotAnalysis.topic == topic,
                    )
                    .first()
                )
                payload = {
                    "strengths": _pick(topic, "strengths", table.number),
                    "weaknesses": _pick(topic, "weaknesses", table.number),
                    "opportunities": _pick(topic, "opportunities", table.number),
                    "threats": _pick(topic, "threats", table.number),
                }
                if row is None:
                    session.add(
                        SwotAnalysis(
                            table_id=table.id,
                            user_id=user.id,
                            topic=topic,
                            **payload,
                        )
                    )
                    created += 1
                elif force:
                    row.strengths = payload["strengths"]
                    row.weaknesses = payload["weaknesses"]
                    row.opportunities = payload["opportunities"]
                    row.threats = payload["threats"]
                    updated += 1
                else:
                    skipped += 1

        session.commit()
        return {
            "ok": True,
            "user": user.email,
            "tables": len(tables),
            "topics": len(SWOT_TOPICS),
            "created": created,
            "updated": updated,
            "skipped": skipped,
        }
    except Exception as exc:
        session.rollback()
        return {"ok": False, "error": str(exc)}
    finally:
        session.close()
